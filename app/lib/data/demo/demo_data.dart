  static Pothole _pothole(
    int id,
    double latitude,
    double longitude,
    String address,
    PotholeStatus status,
    int severity,
    int reports,
    DateTime lastReported, [
    String? photo,
  ]) {
    return Pothole(
      id: id,
      status: status,
      severity: severity,
      reportCount: reports,
      latitude: latitude,
      longitude: longitude,
      address: address,
      firstReportedAt: lastReported.subtract(Duration(days: reports)),
      lastReportedAt: lastReported,
      fixedAt: status == PotholeStatus.fixed
          ? lastReported.add(const Duration(days: 1))
          : null,
      photoUrl: photo == null ? null : 'asset://assets/demo/$photo.webp',
    );
  }
